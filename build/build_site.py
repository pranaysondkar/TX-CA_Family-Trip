"""Writes ../data.js (window.TRIP) from trip_data.py for index.html.

Run:  python build_site.py
The home address is never written; "Home (Del Valle)" becomes "Home (Austin)".
"""
import json
import os

import trip_data as T

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "data.js")


def public(s):
    return s.replace("Home (Del Valle)", "Home (Austin)").replace("Del Valle", "Austin")


import urllib.parse

ROUTE_DATA = json.load(open(os.path.join(HERE, "routes.json")))


def gmaps(stops):
    pt = lambda k: f"{T.P[k][1]},{T.P[k][2]}"
    q = {"api": "1", "origin": pt(stops[0]), "destination": pt(stops[-1]), "travelmode": "driving"}
    if len(stops) > 2:
        q["waypoints"] = "|".join(pt(k) for k in stops[1:-1])
    return "https://www.google.com/maps/dir/?" + urllib.parse.urlencode(q, safe=",|")


days = []
for d in T.DAYS:
    d = dict(d)
    d["stay"], d["title"], d["drive"] = public(d["stay"]), public(d["title"]), public(d["drive"])
    d["plan"] = [public(p) for p in d["plan"]]
    d["tips"] = [public(t) for t in d["tips"]]
    d["links"] = [{"key": k, "url": T.L[k]} for k in d["links"] if k in T.L]
    stops = T.ROUTES.get(d["date"])
    if stops:
        r = ROUTE_DATA[d["date"]]
        d["route"] = dict(stops=[dict(name=T.P[k][0], lat=T.P[k][1], lon=T.P[k][2]) for k in stops],
                          line=r["line"], miles=r["miles"], minutes=r["minutes"], legs=r["legs"], gmaps=gmaps(stops))
    days.append(d)

cats = {}
for (cat, item, dates, qty, unit, tax, status, lean, lk, note) in T.BUDGET:
    planned = 0 if status == "Optional" else qty * unit * (1 + tax)
    c = cats.setdefault(cat, {"planned": 0, "lean": 0})
    c["planned"] += planned
    c["lean"] += planned if lean is None else lean

lines = [dict(id=T.budget_id(cat, item), cat=cat, item=public(item), planned=round(qty * unit * (1 + tax), 2),
              inPlan=status != "Optional", lean=round(qty * unit * (1 + tax) if lean is None else lean, 2))
         for (cat, item, dates, qty, unit, tax, status, lean, lk, note) in T.BUDGET]

todo = [dict(id=T.budget_id(cat, item), item=public(item), dates=dates, status=status, url=T.L.get(lk), cost=round(qty * unit * (1 + tax)))
        for (cat, item, dates, qty, unit, tax, status, lean, lk, note) in T.BUDGET
        if status in ("To book", "Reserve", "Book", "Book early", "Confirm", "Decide", "Get quote", "Buy", "Buy at gate", "Pay online")]

credits = json.load(open(os.path.join(HERE, "..", "img", "credits.json")))
data = dict(checked=T.PRICES_CHECKED, budget=T.BUDGET_TOTAL, days=days,
            categories=[dict(name=k, planned=round(v["planned"]), lean=round(v["lean"])) for k, v in cats.items()],
            todo=todo, lines=lines, bookingsCsv=T.BOOKINGS_CSV, bookingsEdit=T.BOOKINGS_EDIT, climate=T.CLIMATE, alertsNote=T.ALERTS_NOTE, credits=credits,
            quick=[{"label": a, "url": T.L[b]} for a, b in [
                ("Caltrans QuickMap", "quickmap"), ("Chain controls", "chains"), ("Sequoia roads", "seki_roads"),
                ("Sequoia alerts", "seki_conditions"), ("NWS", "nws"), ("FasTrak toll pay", "fastrak"),
                ("DFW cell lot", "dfw_cell"), ("Trail of Lights", "trail_lights")]])
with open(OUT, "w") as f:
    f.write("// Generated by build/build_site.py. Edit trip_data.py, not this file.\n")
    f.write("window.TRIP = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
print("wrote", os.path.abspath(OUT))
